#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Generates or checks `THIRD_PARTY_NOTICES.md`.
 *
 * The report is deterministic: no timestamp, sorted package names and one row
 * per package/version. `--check` fails when the checked-in file differs, so a
 * dependency change cannot silently leave stale notices.
 */

const ROOT = resolve(fileURLToPath(import.meta.url), "../..");
const OUTPUT = resolve(ROOT, "THIRD_PARTY_NOTICES.md");

/**
 * Reads one `pnpm licenses list --json` result.
 *
 * @param {string[]} args - Arguments passed to pnpm.
 * @returns {Map<string, { name: string, version: string, license: string, homepage: string }[]>}
 */
function readLicenses(args) {
  const output = execFileSync("pnpm", args, {
    cwd: ROOT,
    encoding: "utf8",
    maxBuffer: 32 * 1024 * 1024,
  });
  const grouped = JSON.parse(output);
  const entries = [];
  for (const [license, packages] of Object.entries(grouped)) {
    for (const pkg of packages) {
      const versions = Array.isArray(pkg.versions) ? pkg.versions : [];
      for (const version of versions) {
        entries.push({
          name: pkg.name ?? "unknown",
          version,
          license: pkg.license ?? license,
          homepage: pkg.homepage ?? "",
        });
      }
    }
  }
  return entries.sort((left, right) =>
    left.name === right.name
      ? left.version.localeCompare(right.version)
      : left.name.localeCompare(right.name),
  );
}

/** Escapes a Markdown table cell. */
function cell(value) {
  return String(value).replaceAll("|", "\\|").replaceAll("\n", " ");
}

/** Renders one license table. */
function table(entries) {
  const lines = ["| Package | Version | License | Homepage |", "|---|---|---|---|"];
  for (const entry of entries) {
    lines.push(
      `| ${cell(entry.name)} | ${cell(entry.version)} | ${cell(entry.license)} | ${cell(entry.homepage)} |`,
    );
  }
  return lines;
}

/** Builds the complete notices document. */
function render() {
  const runtime = readLicenses(["-r", "licenses", "list", "--prod", "--json"]);
  const development = readLicenses(["-r", "licenses", "list", "--dev", "--json"]);
  const lines = [
    "# Third-Party Notices",
    "",
    "This project uses the [Year Planner Internal Use License 1.0](LICENSE).",
    "Third-party dependencies retain their own licenses; the project license does not replace them.",
    "The published library bundles no third-party runtime code;",
    "React and React DOM are peer dependencies supplied by the host application. The demo's",
    "direct dependencies are included in the development table because the demo is private and",
    "is not published.",
    "",
    "## Runtime dependencies",
    "",
    ...(runtime.length ? table(runtime) : ["No third-party runtime dependencies are bundled."]),
    "",
    "## Development tooling and demo dependencies (not published)",
    "",
    ...table(development),
    "",
    "## Palette attribution (data only, no bundled code)",
    "",
    "The `material-*` presets use colour values from the Material Design 2014",
    "named palette published by MUI (MIT):",
    "<https://mui.com/material-ui/customization/color/>.",
    "",
    "The `fluent-*` presets use colour values from the public Fluent UI v9",
    "`webLightTheme` token set (MIT): <https://react.fluentui.dev/>.",
    "",
    "No runtime code from either project is bundled. Their full licence texts",
    "remain available with the upstream distributions and repositories. The React",
    "package ships the same attribution in `packages/react/THIRD_PARTY_NOTICES.md`.",
    "",
    "Generated by `pnpm test:licenses --write`; checked by `pnpm test:licenses`.",
    "",
  ];
  return `${lines.join("\n")}\n`;
}

const write = process.argv.includes("--write");
const expected = render();
if (write) {
  writeFileSync(OUTPUT, expected);
  console.log(`Wrote ${OUTPUT}`);
} else {
  if (!existsSync(OUTPUT)) {
    console.error("THIRD_PARTY_NOTICES.md is missing; run `pnpm test:licenses --write`");
    process.exit(1);
  }
  const actual = readFileSync(OUTPUT, "utf8");
  if (actual !== expected) {
    console.error("THIRD_PARTY_NOTICES.md is stale; run `pnpm test:licenses --write`");
    process.exit(1);
  }
  console.log("THIRD_PARTY_NOTICES.md is current");
}
